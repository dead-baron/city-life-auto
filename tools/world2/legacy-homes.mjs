// Writes server/systems/legacy-homes.js: the homes of an earlier world by index - what each one cost and what it was
// called - so a profile that bought a home there is bought back at the right price when the world changes under it,
// and told which home went (server/systems/homes.js checkWorld: the deed's price first, the name from here).
//   world v1 (the world before World v2: profiles from before deeds were kept refer to their homes only by index) -
//     run once against a checkout of the old world: node tools/world2/legacy-homes.mjs [--root <dir>]
//   world v9 (today's world, before World v3's bump: docs/WORLD-V3.md 8.23, step 0 d) - from this checkout's world:
//     node tools/world2/legacy-homes.mjs --wv 9
// The other worlds' lists in the file are kept as they are.
import { writeFileSync } from 'node:fs';
import { resolve, join } from 'node:path';
import { pathToFileURL } from 'node:url';

const args = process.argv.slice(2);
const opt = (k, d) => { const i = args.indexOf(k); return i >= 0 ? args[i + 1] : d; };
const root = resolve(opt('--root', new URL('../..', import.meta.url).pathname));
const wv = Number(opt('--wv', 1));
const out = resolve(new URL('../../server/systems/legacy-homes.js', import.meta.url).pathname);
const { LEGACY_HOMES } = await import(pathToFileURL(out).href);
const { generateCity } = await import(pathToFileURL(join(root, 'shared/map.js')).href);
const m = generateCity(1337);
const lists = { ...LEGACY_HOMES, [wv]: m.homes.map((h) => [h.price, h.name]) };
const body = Object.keys(lists).map(Number).sort((a, b) => a - b).map((v) => ` ${v}: [\n${lists[v].map(([price, name]) => `  [${price}, ${JSON.stringify(name)}],`).join('\n')}\n ],`).join('\n');
writeFileSync(out, `// GENERATED by tools/world2/legacy-homes.mjs - do not edit by hand.
// The homes of earlier worlds by index - world version: [[price paid, name], ...] by home index. When the world changes
// under a profile (server/systems/homes.js checkWorld), its homes are bought back at their deeds (or, for world v1's
// homes bought before deeds were kept, at the price here) and the note names them from here.
//   1  world v1, the world before World v2
//   9  today's world before World v3 (docs/WORLD-V3.md 8.23)
export const LEGACY_HOMES = {
${body}
};
`);
console.log(`${out}: world ${wv}, ${m.homes.length} homes (the file: worlds ${Object.keys(lists).join(', ')})`);
